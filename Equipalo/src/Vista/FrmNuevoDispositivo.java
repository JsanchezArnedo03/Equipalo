    private void cargarComboBox(JComboBox c) {
        List<String> tipoDispositivos = tipoDispositivoService.getAllTipoDispositivo();
        for (int i = 0; tipoDispositivos.size() > i; i++) {
            c.addItem(tipoDispositivos.get(i));
        }
    }

