    private void cargarTabla(JTable table) {
        SolicitudService service = new SolicitudService();
        List<Solicitudes> lista = service.listarSolicitudes();

        DefaultTableModel model = (DefaultTableModel) tblInformes.getModel();
        model.setRowCount(0); // Limpiar tabla

        for (Solicitudes sol : lista) {
            String nombreEmpleado = sol.getEmpleadoSolicita() != null
                    ? sol.getEmpleadoSolicita().getNombreCompleto()
                    : "N/A";

            String nombreDispositivo = sol.getDispositivoSolicitado() != null
                    ? sol.getDispositivoSolicitado().getNombreDispositivo()
                    : "N/A";

            String estado = sol.getEstadoSolicitud() != null
                    ? sol.getEstadoSolicitud().getEstadoSolicitud()
                    : "N/A";

            Object[] fila = new Object[]{
                sol.getCodSolicitud(),
                nombreEmpleado,
                nombreDispositivo,
                sol.getFechaCreacionSolicitud(),
                sol.getFechaSolicitada(),
                estado
            };

            model.addRow(fila);
        }
    }

